# ------------------------------------------------------------------ rigid-body algebra (m kg, c mm, Ic kg m2 about own CG)
def pa(m, d_mm):
    d = np.asarray(d_mm, float) * 1e-3
    return m * (d @ d * np.eye(3) - np.outer(d, d))


def combine(bodies):
    """bodies: [(m, c, Ic)], negative m allowed (removal)."""
    M = sum(b[0] for b in bodies)
    c = sum(b[0] * np.asarray(b[1], float) for b in bodies) / M
    I = sum(np.asarray(b[2], float) + pa(b[0], np.asarray(b[1], float) - c) for b in bodies)
    return M, c, I


def box(m, dims_mm):
    a, b, c = (x * 1e-3 for x in dims_mm)
    return m / 12.0 * np.diag([b * b + c * c, a * a + c * c, a * a + b * b])


def about_pivot(M, c, I):
    return I + pa(M, c)


def polar(r, az_deg, z):
    a = math.radians(az_deg)
    return [r * math.cos(a), r * math.sin(a), z]


