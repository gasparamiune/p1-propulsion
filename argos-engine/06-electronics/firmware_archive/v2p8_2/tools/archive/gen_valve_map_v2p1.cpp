// ARCHIVED 2026-10-12 (firmware v2.5): the v2.1 valve-map GENERATOR, kept for provenance. Since v2.5 the ECU table comes
// from Combustion's throttle_map_v2.csv (tools/gen_tables.py) and sil/gen_valve_map.cpp is a cross-check only.
// Original header follows.
// Generates src/core/valve_map_table.h: steady-state pintle lift for (Pc_abs setpoint, tank pressure) and the
// local plant gain dPc/dx, from the SIL engine plant (which reproduces Combustion's lumped v1 model: Dyer flux,
// lumped helical port, CEA c*). Initial port diameter. Also prints a cross-check against Combustion's throttle map.
// Usage: gen_valve_map <out_header> [combustion throttle_map csv]
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>
#include "plant.h"
#include "plant_tables.h"

using namespace sil;

static double Tsat(double P) {   // invert the saturation table
  double lo = 245.0, hi = 307.0;
  for (int i = 0; i < 60; ++i) { const double m = 0.5 * (lo + hi); if (satP(m) > P) hi = m; else lo = m; }
  return 0.5 * (lo + hi);
}

int main(int argc, char** argv) {
  if (argc < 2) { std::fprintf(stderr, "usage: %s out.h [throttle_map.csv]\n", argv[0]); return 2; }
  EngineParams ep;
  EnginePlant eng(ep);
  const std::vector<double> pc_bar = {3.5, 4.0, 4.5, 5.0, 5.5, 6.0, 7.0, 8.0, 9.0, 10.0, 12.0, 14.0, 16.0, 18.0, 20.0, 22.0, 24.0, 26.0, 28.0};
  const std::vector<double> pt_bar = {24, 28, 32, 36, 40, 44, 48, 52, 56, 60, 64};
  const double xmax = 4.2e-3;
  auto pcss = [&](double T, double x) { double pc; eng.steadyState(T, x, &pc, nullptr, nullptr, nullptr); return pc; };
  std::vector<std::vector<double>> L(pt_bar.size(), std::vector<double>(pc_bar.size())), G = L;
  int sat_count = 0;
  for (size_t j = 0; j < pt_bar.size(); ++j) {
    const double T = Tsat(pt_bar[j] * 1e5);
    for (size_t i = 0; i < pc_bar.size(); ++i) {
      const double target = pc_bar[i] * 1e5;
      double lo = 0.0, hi = xmax;
      double x;
      if (pcss(T, hi) < target) { x = hi; ++sat_count; }
      else {
        for (int it = 0; it < 50; ++it) { const double m = 0.5 * (lo + hi); if (pcss(T, m) > target) hi = m; else lo = m; }
        x = 0.5 * (lo + hi);
      }
      const double d = 5e-6;
      const double xa = std::max(1e-6, x - d), xb = std::min(xmax, x + d);
      G[j][i] = (pcss(T, xb) - pcss(T, xa)) / (xb - xa);
      L[j][i] = x;
    }
  }
  std::ofstream f(argv[1]);
  f << "// GENERATED by sil/gen_valve_map from the SIL plant (combustion.json-derived tables) - DO NOT EDIT.\n"
       "// Steady-state pintle lift [m] and plant gain dPc/dx [Pa/m] vs absolute Pc setpoint and absolute tank pressure,\n"
       "// lit engine, initial port. Saturated cells (setpoint unreachable at that tank pressure) hold the 4.2 mm stop.\n"
       "// To be replaced by cold-flow + static-fire characterisation (same layout).\n#pragma once\nnamespace ecu {\nnamespace vmap {\n";
  f << "constexpr int kNPc = " << pc_bar.size() << ", kNPt = " << pt_bar.size() << ";\n";
  f << "constexpr float kPcGrid_Pa[kNPc] = {";
  char gb[48];
  for (size_t i = 0; i < pc_bar.size(); ++i) { std::snprintf(gb, sizeof gb, "%s%.1ff", i ? ", " : "", pc_bar[i] * 1e5); f << gb; }
  f << "};\nconstexpr float kPtGrid_Pa[kNPt] = {";
  for (size_t j = 0; j < pt_bar.size(); ++j) { std::snprintf(gb, sizeof gb, "%s%.1ff", j ? ", " : "", pt_bar[j] * 1e5); f << gb; }
  f << "};\n";
  char buf[64];
  f << "constexpr float kLift_m[kNPt][kNPc] = {\n";
  for (size_t j = 0; j < pt_bar.size(); ++j) {
    f << "  {";
    for (size_t i = 0; i < pc_bar.size(); ++i) { std::snprintf(buf, sizeof buf, "%s%.4ef", i ? ", " : "", L[j][i]); f << buf; }
    f << "}" << (j + 1 < pt_bar.size() ? ",\n" : "\n");
  }
  f << "};\nconstexpr float kGain_Pa_per_m[kNPt][kNPc] = {\n";
  for (size_t j = 0; j < pt_bar.size(); ++j) {
    f << "  {";
    for (size_t i = 0; i < pc_bar.size(); ++i) { std::snprintf(buf, sizeof buf, "%s%.4ef", i ? ", " : "", G[j][i]); f << buf; }
    f << "}" << (j + 1 < pt_bar.size() ? ",\n" : "\n");
  }
  f << "};\n}  // namespace vmap\n}  // namespace ecu\n";
  std::printf("valve map written: %zu x %zu, %d saturated cells\n", pt_bar.size(), pc_bar.size(), sat_count);
  // ---- cross-check against Combustion's throttle map (h vs Pc at T)
  if (argc >= 3) {
    std::ifstream c(argv[2]);
    if (!c.good()) { std::printf("CHECK NOT RUN: cannot read %s\n", argv[2]); return 0; }
    std::string line; std::vector<std::string> hdr;
    double maxerr = 0;
    while (std::getline(c, line)) {
      if (line.empty() || line[0] == '#') continue;
      std::vector<std::string> v; std::stringstream ss(line); std::string tok;
      while (std::getline(ss, tok, ',')) v.push_back(tok);
      if (hdr.empty()) { hdr = v; continue; }
      auto col = [&](const char* n) { for (size_t k = 0; k < hdr.size(); ++k) if (hdr[k] == n) return std::atof(v[k].c_str()); return 0.0; };
      const double T = col("T_tank"), Pc = col("Pc"), h = col("h"), F = col("F");
      double lo = 0, hi = xmax;
      for (int it = 0; it < 50; ++it) { const double m = 0.5 * (lo + hi); if (pcss(T, m) > Pc) hi = m; else lo = m; }
      const double x = 0.5 * (lo + hi);
      double pc2, mo, mf, F2; eng.steadyState(T, h, &pc2, &mo, &mf, &F2);
      const double err_um = (x - h) * 1e6;
      if (std::fabs(err_um) > maxerr) maxerr = std::fabs(err_um);
      std::printf("CHECK T=%.2f F=%6.1f Pc=%6.3f bar: comb lift %.4f mm, SIL lift %.4f mm (%+.1f um); SIL at comb lift: Pc %.3f bar F %.1f N\n",
                  T, F, Pc / 1e5, h * 1e3, x * 1e3, err_um, pc2 / 1e5, F2);
    }
    std::printf("CHECK max |lift error| = %.1f um\n", maxerr);
  }
  return 0;
}
