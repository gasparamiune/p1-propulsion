"""Generate TVC geometry constants (firmware) and gimbal load tables (SIL) from interfaces/mechanical.json.

Electronics v2.1, 2026-10-12. Reads (never hard-codes Mechanical's numbers):
  interfaces/mechanical.json  tvc_actuation (lever azimuths/radius/ball z, horn radius, pushrod), gimbal range and
                              stop, gimballed mass properties, hinge-moment terms, feed-hose stiffness range
  interfaces/gnc.json         gimbal requirements (rate, bandwidth, resolution, rocking mode) - already in gnc_tables.h
Writes:
  src/core/mech_params.h      firmware: Cardan TVC kinematics constants (servo mixing)
  sil/mech_tables.h           SIL: 2-axis gimbal plant parameters
  ../results/gen_mech_params_v1.json  provenance (sha of mechanical.json, values, derived checks)
Usage: python3 gen_mech_params.py [--engine-root <engine dir with interfaces/>]
"""
import argparse
import datetime
import hashlib
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
RES = os.path.join(FW, '..', 'results')


def v(node):
    return node['v'] if isinstance(node, dict) and 'v' in node else node


def cardan_dz(a, b, r, phi, zb):
    """Vertical displacement of the lever ball (azimuth phi, radius r, height zb) for R = Rx(a) Ry(b)."""
    x0, y0, z0 = r * math.cos(phi), r * math.sin(phi), zb
    z1 = -x0 * math.sin(b) + z0 * math.cos(b)
    z2 = y0 * math.sin(a) + z1 * math.cos(a)
    return z2 - z0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--engine-root', default=os.environ.get('ENGINE_ROOT', '/home/claude/work/shared-fallback/engine'))
    args = ap.parse_args()
    fn = os.path.join(args.engine_root, 'interfaces', 'mechanical.json')
    raw = open(fn, 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()[:16]
    m = json.loads(raw)
    ver = m.get('version', '?')
    tvc = m['tvc_actuation']
    gim = m['gimbal']
    mp = m['gimballed_mass_properties']
    hm = tvc['hinge_moment_terms_Nm']
    az = [math.radians(a) for a in v(tvc['lever_azimuth_deg'])]
    r_e = v(tvc['lever_radius_m'])
    z_b = v(tvc['lever_ball_z_m'])
    r_h = v(tvc['horn_radius_m'])
    rod = v(tvc['pushrod_length_m'])
    n = v(tvc['gear_ratio_n'])
    rng = math.radians(v(gim['range_deg']))
    stop = math.radians(v(gim['mechanical_stop_deg']))
    I_wet = v(mp['wet_full_grain']['I_pivot_kgm2'])
    I_dry = v(mp['dry_grain_burnt']['I_pivot_kgm2'])
    I_ring = v(mp['ring_alpha_axis_only']['I_xx_kgm2'])
    k_hose = v(m['feed_across_gimbal']['hinge_stiffness_Nm_per_rad'])
    # derived checks (independent of Mechanical's own numbers, compared below)
    worst = 0.0
    for k in range(360):
        th = math.radians(k)
        a, b = rng * math.cos(th), rng * math.sin(th)
        for i in range(2):
            dz = cardan_dz(a, b, r_e, az[i], z_b)
            worst = max(worst, abs(math.degrees(math.asin(min(1.0, abs(dz) / r_h)))))
    worst_stop = 0.0
    for k in range(360):
        th = math.radians(k)
        a, b = stop * math.cos(th), stop * math.sin(th)
        for i in range(2):
            dz = cardan_dz(a, b, r_e, az[i], z_b)
            worst_stop = max(worst_stop, math.degrees(math.asin(min(1.0, abs(dz) / r_h))))
    lin_err = 0.0   # linear vs exact ball displacement at the range
    for k in range(360):
        th = math.radians(k)
        a, b = rng * math.cos(th), rng * math.sin(th)
        for i in range(2):
            ex = cardan_dz(a, b, r_e, az[i], z_b)
            li = r_e * (math.sin(az[i]) * a - math.cos(az[i]) * b)
            lin_err = max(lin_err, abs(ex - li))
    axacc_per_rad = v(hm['axial_accel_m_a_le_sin7']) / math.sin(rng)
    date = datetime.date.today().isoformat()
    src = 'mechanical.json %s sha %s' % (ver, sha)
    fwh = f'''// GENERATED by firmware/tools/gen_mech_params.py - DO NOT EDIT. Regenerate when mechanical.json changes.
// Source: {src}, date {date}. Units SI. Tag [MECH] = mechanical.json value, [DERIVED] = computed here.
#pragma once
namespace ecu {{
namespace mech {{
// Cardan gimbal R = Rx(alpha) Ry(beta); alpha = outer axis (ring pins, +X), beta = inner axis (collar pins, +Y).
// Each TVC servo drives a vertical pushrod to a lever ball on the engine collar at azimuth kLeverAz_rad[i].
constexpr float kLeverAz_rad[2] = {{{az[0]:.6f}f, {az[1]:.6f}f}};   // [MECH] {v(tvc['lever_azimuth_deg'])} deg
constexpr float kLeverR_m = {r_e:.6f}f;        // [MECH] lever (ball) radius from the engine axis
constexpr float kLeverBallZ_m = {z_b:.6f}f;    // [MECH] ball height in the engine frame (pivot = 0)
constexpr float kHornR_m = {r_h:.6f}f;         // [MECH] servo horn radius
constexpr float kPushrod_m = {rod:.6f}f;       // [MECH] ball-to-ball (rod tilt neglected in the firmware map)
constexpr float kGearRatio = {n:.4f}f;          // [MECH] r_e / r_h (small-angle)
constexpr float kRangeVec_rad = {rng:.6f}f;    // [MECH/GNC] commanded limit on the VECTOR norm
constexpr float kStopCone_rad = {stop:.6f}f;   // [MECH] conical mechanical stop
constexpr float kServoAtRange_deg = {worst:.2f}f;  // [DERIVED] worst servo angle at the range (MECH quotes {v(tvc['servo_angle_at_7deg_vector_worst_deg'])})
constexpr float kServoAtStop_deg = {worst_stop:.2f}f;   // [DERIVED] worst servo angle at the stop (MECH quotes {v(tvc['servo_angle_at_8deg_stop_deg'])})
}}  // namespace mech
}}  // namespace ecu
'''
    open(os.path.join(FW, 'src', 'core', 'mech_params.h'), 'w').write(fwh)
    silh = f'''// GENERATED by firmware/tools/gen_mech_params.py - DO NOT EDIT. SIL 2-axis gimbal plant from {src}.
#pragma once
namespace sil {{
namespace mech {{
constexpr double k_I_wet_kgm2[2] = {{{I_wet[0][0]:.6e}, {I_wet[1][1]:.6e}}};   // [MECH] Ixx, Iyy about the pivot, full grain
constexpr double k_I_dry_kgm2[2] = {{{I_dry[0][0]:.6e}, {I_dry[1][1]:.6e}}};   // [MECH] grain burnt
constexpr double k_I_ring_alpha_kgm2 = {I_ring:.6e};   // [MECH ASSUMED] ring adds to the alpha (outer) axis only
constexpr double k_K_hose_Nm_per_rad[2] = {{{k_hose[0]:.4f}, {k_hose[1]:.4f}}};   // [MECH ASSUMED range] feed hose
constexpr double k_M_fric_bearing_Nm = {v(hm['bearing_seal_friction']):.4f};   // [MECH ASSUMED] 2 x 608-2RS seal drag per axis
constexpr double k_M_mis_full_Nm = {v(hm['thrust_misalignment']):.4f};         // [MECH] thrust misalignment at 500 N
constexpr double k_M_side_floor_Nm = {v(hm['nozzle_side_load_floor']):.4f};    // [MECH] separation side load (floor)
constexpr double k_M_lat_Nm = {v(hm['lateral_accel_m_alat_le']):.4f};          // [MECH] 1.5 g lateral x l_e
constexpr double k_M_vehacc_Nm = {v(hm['vehicle_angular_accel_Ipivot_x_omegadot']):.4f};   // [MECH] vehicle angular accel
constexpr double k_K_axacc_Nm_per_rad = {axacc_per_rad:.4f};   // [DERIVED] MECH axial-accel term / sin(range)
constexpr double k_hinge_design_Nm = {v(tvc['hinge_moment_design_Nm']):.4f};   // [MECH] linear worst-case sum
constexpr double k_servo_torque_design_Nm = {v(tvc['servo_torque_design_Nm']):.4f};   // [MECH]
constexpr double k_lever_r_m = {r_e:.6f}, k_lever_z_m = {z_b:.6f}, k_horn_r_m = {r_h:.6f};   // [MECH]
constexpr double k_lever_az_rad[2] = {{{az[0]:.6f}, {az[1]:.6f}}};   // [MECH]
constexpr double k_stop_rad = {stop:.6f};   // [MECH] conical stop
}}  // namespace mech
}}  // namespace sil
'''
    open(os.path.join(FW, 'sil', 'mech_tables.h'), 'w').write(silh)
    prov = {'generator': 'firmware/tools/gen_mech_params.py v1', 'date': date, 'mechanical_json': {'version': ver, 'sha256_16': sha},
            'firmware': {'lever_az_deg': v(tvc['lever_azimuth_deg']), 'lever_r_m': r_e, 'lever_ball_z_m': z_b, 'horn_r_m': r_h,
                         'pushrod_m': rod, 'gear_ratio': n, 'range_vec_deg': v(gim['range_deg']),
                         'stop_deg': v(gim['mechanical_stop_deg'])},
            'checks': {'servo_deg_at_range_worst_exact_cardan': round(worst, 2),
                       'servo_deg_at_range_worst_mechanical': v(tvc['servo_angle_at_7deg_vector_worst_deg']),
                       'servo_deg_at_stop_worst_exact_cardan': round(worst_stop, 2),
                       'servo_deg_at_stop_mechanical': v(tvc['servo_angle_at_8deg_stop_deg']),
                       'linear_vs_exact_ball_dz_max_mm': round(lin_err * 1e3, 4),
                       'servo_operating_half_travel_deg': 50.0, 'servo_max_half_travel_deg': 65.0},
            'sil': {'I_wet': [I_wet[0][0], I_wet[1][1]], 'I_dry': [I_dry[0][0], I_dry[1][1]], 'I_ring_alpha': I_ring,
                    'K_hose_range': k_hose, 'K_axacc_per_rad': axacc_per_rad}}
    os.makedirs(RES, exist_ok=True)
    json.dump(prov, open(os.path.join(RES, 'gen_mech_params_v1.json'), 'w'), indent=1)
    print(json.dumps(prov['checks'], indent=1))


if __name__ == '__main__':
    main()
