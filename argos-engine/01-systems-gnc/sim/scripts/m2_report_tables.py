"""Markdown tables for REPORT.md, transcribed by script from the M2 outputs (no hand-copied numbers).

Reads the same files as m2_gnc_json.py plus gnc_v2.json; writes GNC_RES/report_tables_v2.md with one section per
table. Run after m2_gnc_json.py: python scripts/m2_report_tables.py
"""
import csv
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

OUT = os.environ.get("GNC_OUT", "/home/claude/work/space/out/m2")
RES = os.environ.get("GNC_RES", "/home/claude/work/space/out/results_v2")
DCO = os.environ.get("GNC_DC_OUT", "/home/claude/work/space/out/duty_cycles_v2")
VEH = os.environ.get("GNC_VEH_OUT", "/home/claude/work/space/out/vehicle")
GJ = os.path.join(os.path.dirname(OUT), "gnc_json", "gnc_v2.json")


def jl(p):
    try:
        return json.load(open(p))
    except (OSError, ValueError):
        return None


def rc(p):
    try:
        return list(csv.DictReader(open(p)))
    except OSError:
        return []


def f(x, n=3):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return "-" if x in (None, "") else str(x)
    if x != x:
        return "-"
    return f"{x:.{n}f}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def main():
    T = jl(os.path.join(RES, "mc6_cases_summary_v2.json"))["cases"]
    S = jl(os.path.join(OUT, "mc6_summary_v2.json"))
    md = ["# Report tables v2 (generated by scripts/m2_report_tables.py; do not edit by hand)\n"]
    # MC cases
    rows = []
    for t in T:
        if "success" not in t:
            rows.append([t["case"], t.get("note", ""), "no closure", "", "", "", "", "", "", ""])
            continue
        rows.append([t["case"], t["note"], f"{f(t['success'])} [{f(t['ci95_lo'])}, {f(t['ci95_hi'])}]",
                     f(t.get("paired_delta_vs_base"), 3) if t.get("paired_delta_vs_base") is not None else "base",
                     f(t.get("mcnemar_p_vs_base"), 3) if t.get("mcnemar_p_vs_base") is not None else "-",
                     f(t["m_n2o_sized_kg"], 3), f(t["m_n2o_mc_kg"], 3), t["fail_modes"].replace(";", "; "),
                     f(t["td_vh_p99"], 2), f(t["td_miss_p50"], 0)])
    md.append("## MC cases\n")
    md.append(table(["case", "configuration", "P [Wilson 95 %]", "paired dP vs base", "McNemar p", "N2O sized kg",
                     "N2O MC kg", "failure modes (count)", "vh p99 m/s", "miss p50 m"], rows))
    # baseline percentiles
    b = S["cases"]["AD_fins_f20"]["summary"]
    keys = [("td_vz_p50", "touchdown |vz| p50 [m/s]"), ("td_vz_p99", "touchdown |vz| p99 [m/s]"),
            ("td_vh_p50", "touchdown v_h p50 [m/s]"), ("td_vh_p99", "touchdown v_h p99 [m/s]"),
            ("td_tilt_p99", "touchdown tilt p99 [deg]"), ("td_rate_p99", "touchdown tilt rate p99 [deg/s]"),
            ("td_miss_p50", "miss p50 [m]"), ("td_miss_p95", "miss p95 [m]"), ("prop_used_p50", "propellant used p50 [kg]"),
            ("prop_used_p99", "propellant used p99 [kg]"), ("liq_left_p01", "liquid left p01 [kg]"),
            ("h_max_p01", "apogee p01 [m]"), ("h_max_p50", "apogee p50 [m]"), ("h_max_p99", "apogee p99 [m]"),
            ("h_ign_p50", "relight height p50 [m]"), ("v_ign_p50", "relight speed p50 [m/s]"),
            ("max_gim_p99", "engine angle p99 [deg]"), ("max_gim_max", "engine angle max [deg]"),
            ("max_gim_rate_p99", "engine rate p99 [deg/s]"), ("max_gim_acc_p99", "engine angular accel p99 [rad/s2]"),
            ("gim_sat_frac_p99", "saturated fraction of burn p99"), ("max_hinge_p99", "mount torque lit p99 [N m]"),
            ("max_hinge_max", "mount torque lit max [N m]"), ("max_hinge_td_p99", "mount torque after touchdown p99 [N m]"),
            ("max_hinge_td_max", "mount torque after touchdown max [N m]"),
            ("max_axial_g_flt_p99", "axial flight p99 [g]"), ("max_axial_g_flt_max", "axial flight max [g]"),
            ("max_axial_g_td_p99", "axial touchdown p99 [g]"), ("max_axial_g_td_max", "axial touchdown max [g]"),
            ("max_lat_g_eng_flt_p99", "lateral at pivot flight p99 [g]"), ("max_lat_g_eng_flt_max", "lateral at pivot flight max [g]"),
            ("max_lat_g_eng_td_p99", "lateral at pivot touchdown p99 [g]"), ("max_lat_g_eng_td_max", "lateral at pivot touchdown max [g]"),
            ("max_alpha_flt_p99", "body angular accel flight p99 [rad/s2]"), ("max_alpha_td_max", "body angular accel touchdown max [rad/s2]"),
            ("peak_leg_force_p99", "leg force total p99 [N]"), ("peak_leg_force_max", "leg force total max [N]"),
            ("max_rate_coast_p50", "coast body rate p50 [deg/s]"), ("max_rate_coast_p99", "coast body rate p99 [deg/s]"),
            ("max_roll_rate_p99", "roll rate p99 [deg/s]"), ("td_roll_rate_p99", "touchdown roll rate p99 [deg/s]"),
            ("rcs_time_p99", "RCS firing time p99 [s]"), ("max_q_p99", "max dynamic pressure p99 [Pa]"),
            ("hslam_frac", "fraction of runs in hoverslam"), ("tumble_coast", "fraction tumbling in coast")]
    bl = S["cases"].get("AD_prov_2kg", {}).get("summary", {})
    md.append("\n## Baseline percentiles: AD_fins_f20 (RCS fitted, sized load) and AD_prov_2kg (lead baseline)\n")
    md.append(table(["metric", "AD_fins_f20", "AD_prov_2kg"], [[lab, f(b.get(k), 3), f(bl.get(k), 3)] for k, lab in keys]))
    # by wind
    md.append("\n## Baseline success by wind bin\n")
    md.append(table(["wind [m/s]", "n", "P"], [[f"{w['wind_lo']:.0f}-{w['wind_hi']:.0f}", w["n"], f(w["success"])]
                                               for w in b["by_wind"]]))
    # sensitivity
    sens = S["cases"]["AD_fins_f20"]["sensitivity"]
    md.append("\n## Baseline sensitivity (Spearman rank correlation)\n")
    rows = []
    for k in ("failure", "td_vh", "td_vz", "td_tilt", "td_miss", "prop_used"):
        rows.append([k, "; ".join(f"{a} {c:+.2f}" for a, c in sens.get(k, [])[:6])])
    md.append(table(["output", "top parameters (rho)"], rows))
    # drivers
    D = rc(os.path.join(RES, "mc6_failure_drivers_v2.csv"))
    md.append("\n## Failure drivers (Spearman with the failure indicator; median in failed runs vs all)\n")
    md.append(table(["case", "rank", "parameter", "rho", "median failed", "median all", "n failed"],
                    [[d["case"], d["rank"], d["parameter"], f(d["spearman_rho_with_failure"], 2), f(d["median_in_failed"], 3),
                      f(d["median_all"], 3), d["n_failed"]] for d in D if int(d["rank"]) <= 4]))
    # forensics
    FX = jl(os.path.join(RES, "mc6_failure_forensics_v2.json")) or {}
    md.append("\n## Failure forensics (re-flown failed runs, same draws)\n")
    md.append(table(["case", "run", "reproduced", "wind", "gyro bias deg/s", "reasons"],
                    [[r["case"], r["run"], r["reproduced"], f(r["wind"], 1), f(r["g_bias_dps"], 3), r["reasons"]]
                     for r in FX.get("rows", [])]))
    # roll sweep
    RS = rc(os.path.join(RES, "mc6_roll_sweep_v2.csv"))
    md.append("\n## Roll-control sweep\n")
    md.append(table(["case", "roll amp N m", "RCS", "P [95 %]", "failure modes", "roll rate p99 deg/s", "touchdown tilt rate p99"],
                    [[r["case"], r["roll_amp_Nm"], r["rcs"], f"{f(r['success'])} [{f(r['ci95_lo'])}, {f(r['ci95_hi'])}]",
                      r["fail_modes"], f(r["max_roll_rate_p99_dps"], 1), f(r["td_rate_p99_dps"], 2)] for r in RS]))
    # IMU sweep
    IM = jl(os.path.join(RES, "imu_sweep_v2.json")) or {}
    md.append("\n## IMU sweep (300 runs per point)\n")
    md.append(table(["IMU model", "gyro residual bias deg/s", "P [95 %]", "crashes", "vh p99"],
                    [[r["imu"], f(r["gyro_residual_bias_dps"], 3), f"{f(r['success'])} [{f(r['ci95_lo'])}, {f(r['ci95_hi'])}]",
                      r["crashes"], f(r["td_vh_p99"], 2)] for r in IM.get("rows", [])]))
    # vehicle ledger
    L = rc(os.path.join(VEH, "mass_ledger_v3c.csv"))
    if L:
        md.append("\n## Mass ledger v3c\n")
        k0 = list(L[0].keys())
        md.append(table(k0, [[r[k] for k in k0] for r in L]))
    EV = rc(os.path.join(VEH, "massprops_events_v3c.csv"))
    if EV:
        md.append("\n## Mass properties at events (nominal A-D)\n")
        k0 = list(EV[0].keys())
        md.append(table(k0, [[f(r[k], 4) if k != "event" else r[k] for k in k0] for r in EV]))
    TW = rc(os.path.join(VEH, "twd_table_v2.csv"))
    if TW:
        md.append("\n## Tail-wags-dog table\n")
        k0 = list(TW[0].keys())
        md.append(table(k0, [[r[k] if k in ("state", "F_label") else f(r[k], 4) for k in k0] for r in TW]))
    # verification
    VF = jl(os.path.join(OUT, "verify6_v2.json")) or {}
    if VF:
        md.append("\n## Verification\n")
        rows = []
        for r in VF.get("torque_free", []):
            rows.append(["torque-free kernel (v2.4)", f"dt {r['dt']}", f"|H| drift {r['H_rel_drift_max']:.2e}, T drift {r['Ek_rel_drift_max']:.2e}, "
                                                          f"|q|-1 {r['qnorm_err_max']:.1e}, pass {r.get('pass')}"])
        for r in VF.get("torque_free_v2_3_integrator", []):
            rows.append(["torque-free kernel, v2.3 integrator (evidence)", f"dt {r['dt']}",
                         f"|H| drift {r['H_rel_drift_max']:.2e}, T drift {r['Ek_rel_drift_max']:.2e}: FAIL"])
        for r in VF.get("torque_free_internal_dofs", []):
            rows.append(["torque-free with slosh + flexible mount (info)", f"dt {r['dt']}",
                         f"|H| drift {r['H_rel_drift_max']:.2e}, T drift {r['Ek_rel_drift_max']:.2e}"])
        for r in VF.get("vacuum_ballistic", []):
            rows.append(["vacuum ballistic", f"dt {r['dt']}", f"E drift {r['E_rel_drift_max']:.2e}, z error {r['z_err_max_m']:.2e} m"])
        for r in VF.get("dt_convergence", []):
            rows.append(["dt convergence", f"{r['profile']} dt {r['dt']} wind {r['wind']}",
                         f"td_vz {f(r['td_vz'], 3)}, td_vh {f(r['td_vh'], 3)}, apogee {f(r['h_max'], 2)}, prop {f(r['prop_used'], 4)}"])
        for r in VF.get("zero_dispersion", []):
            rows.append(["zero dispersion", f"{r['profile']} fins {r['fins']}", f"success {r['success']}, td_vz {f(r['td_vz'], 3)}, "
                                                                                  f"prop {f(r['prop_used'], 3)}, apogee {f(r['h_max'], 1)}"])
        for c in VF.get("compare_sim1d", []):
            rows.append(["vs sim1d", c["profile"], "sim6 " + ", ".join(f"{k} {f(c['sim6'][k], 3)}" for k in ("h_max", "prop_used", "h_ign", "v_ign"))
                         + " | sim1d " + ", ".join(f"{k} {f(c['sim1d'][k], 3)}" for k in ("h_max", "prop_used", "h_ign", "v_ign"))])
        ls = VF.get("compare_lead_seed")
        if ls:
            rows.append(["vs lead seed", "A-F", "seed " + ", ".join(f"{k} {f(v, 3)}" for k, v in ls["seed"].items() if isinstance(v, (int, float)))
                         + " | sim6 " + ", ".join(f"{k} {f(ls['sim6_AF'][k], 3)}" for k in ("prop_used", "h_ign", "v_ign", "h_max", "m_land"))])
        md.append(table(["check", "case", "result"], rows))
    # integrator change v2.3 -> v2.4 (same draws)
    IC = rc(os.path.join(RES, "integrator_change_v23_v24.csv"))
    if IC:
        md.append("\n## sim6 v2.3 to v2.4 integrator change (same draws)\n")
        md.append(table(["case", "P v2.3", "P v2.4", "ok to fail", "fail to ok", "max |d vh| m/s", "median |d vh| m/s",
                         "max |d roll rate| deg/s"],
                        [[r["case"], f(r.get("P_v23")), f(r.get("P_v24")), r.get("flipped_ok_to_fail"), r.get("flipped_fail_to_ok"),
                          f(r.get("max_abs_change_td_vh"), 3), f(r.get("median_abs_change_td_vh"), 4),
                          f(r.get("max_abs_change_max_roll_rate"), 2)] for r in IC]))
    # CSI
    CSI = jl(os.path.join(OUT, "csi_v2.json")) or {}
    if CSI:
        md.append("\n## CSI (linear) summary\n")
        rows = [[k, v.get("n_cases"), v.get("n_unstable"), f(v.get("rigid_pm_min_deg"), 1), f(v.get("rigid_gm_up_min_dB"), 1),
                 f(v.get("flex_gm_up_min_dB"), 1)] for k, v in CSI.get("summary", {}).items()]
        md.append(table(["filter", "cases", "unstable", "rigid PM min deg", "rigid GM up min dB", "flex GM up min dB"], rows))
    CTD = jl(os.path.join(OUT, "csi_timedomain_v2.json")) or {}
    if CTD:
        md.append("\n## CSI time domain (6-DOF)\n")
        k0 = list(CTD["rows"][0].keys())
        md.append(table(k0, [[f(r[k], 3) if isinstance(r[k], float) else r[k] for k in k0] for r in CTD["rows"]]))
    # duty cycles
    DCI = jl(os.path.join(DCO, "duty_cycles_index_v2.json")) or {}
    if DCI:
        md.append("\n## Duty cycles v2\n")
        md.append(table(["name", "burn s", "impulse N s", "starts", "max axial m/s2", "max gimbal deg", "success"],
                        [[c["name"], f(c["burn_time_s"], 2), f(c["total_impulse_Ns"], 0), c.get("starts"),
                          f(c.get("max_axial_specific_mps2"), 1), f(c.get("max_gimbal_deg"), 2), c.get("success")]
                         for c in DCI.get("cycles", [])]))
    # fin roll
    FR = jl(os.path.join(RES, "fin_roll_v2.json"))
    if FR:
        md.append("\n## Fin-misalignment roll (hand calculation)\n")
        md.append(table(["cant deg", "one fin N m", "4 fins same sense N m", "x RCS torque", "steady rate at MECO deg/s",
                         "with RCS deg/s", "under drogue deg/s", "tau s"],
                        [[c["cant_deg"], f(c["torque_one_fin_Nm"], 4), f(c["torque_all_fins_same_sense_Nm"], 4),
                          f(c["ratio_to_rcs_torque"], 2), f(c["steady_roll_rate_all_fins_dps"], 1),
                          f(c["steady_roll_rate_with_rcs_dps"], 1), f(c.get("steady_roll_rate_under_drogue_dps"), 1),
                          f(c["tau_s"], 2)] for c in FR["cases"]]))
        tol = FR.get("tolerance")
        if tol:
            md.append(f"\nTolerance: same-sense cant <= {f(tol['cant_max_same_sense_deg'], 3)} deg (rule: {tol['rule']}; roll rate "
                      f"flown p99 {f(tol['roll_rate_flown_p99_dps'], 1)} deg/s; under the drogue at that cant "
                      f"{f(tol['steady_rate_under_drogue_at_tol_dps'], 1)} deg/s).")
    # engine relay
    ER = jl(os.path.join(RES, "engine_relay_v2.json"))
    if ER:
        md.append("\n## Engine relay correction\n")
        md.append(table(["F bin N", "time s", "k_ox", "k_f", "Isp combustion v2 s", "Isp map v1 s", "O/F comb.", "used"],
                        [[f"{b_['F_lo']}-{b_['F_hi']}", f(b_["time_s"], 2), f(b_["k_ox"], 3), f(b_["k_f"], 3), f(b_["Isp_comb"], 1),
                          f(b_["Isp_map_v1"], 1), f(b_["OF_comb"], 2), b_["used"]] for b_ in ER["bins"]]))
        md.append("\n")
        md.append(table(["profile", "N2O per kN s err v1 map %", "after correction %", "Isp corrected s", "Isp combustion s"],
                        [[v["profile"], f(100 * v["ox_per_impulse_err_v1"], 1), f(100 * v["ox_per_impulse_err_corrected"], 2),
                          f(v["map_corrected"]["Isp_s"], 1), f(v["combustion"]["Isp_s"], 1)] for v in ER["validation"]]))
    # gnc.json requirements flattened
    G = jl(GJ)
    if G:
        md.append("\n## gnc.json v2 requirements (flattened)\n")
        rows = []
        for grp, d in G["requirements"].items():
            for k, v in d.items():
                if isinstance(v, dict) and "v" in v:
                    val = v["v"]
                    if isinstance(val, (dict, list)):
                        val = json.dumps(val)[:160]
                    rows.append([grp, k, str(val)[:200], v.get("tag", "")[:120]])
        md.append(table(["group", "key", "value", "tag"], rows))
    with open(os.path.join(RES, "report_tables_v2.md"), "w") as fo:
        fo.write("\n".join(md) + "\n")
    print("written", os.path.join(RES, "report_tables_v2.md"))


if __name__ == "__main__":
    main()
