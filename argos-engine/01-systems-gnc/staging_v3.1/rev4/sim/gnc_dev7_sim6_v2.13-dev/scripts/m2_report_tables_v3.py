"""Markdown tables for the gnc.json v3 state of the GNC report (transcribed by script; no hand-copied numbers).

Sections (one '## title' block each, used by m2_report_assemble_v3.py as TAB@v3:title):
  Re-baseline attribution            v2 (gnc.json v2 runs) -> v3a (combustion.json v2.1 on mechanical.json v1)
                                     -> v3 (combustion.json v2.1 + mechanical.json v2), paired on the same draws
  Vehicle re-baseline                ledger sums, pivot, CG, tail-wags-dog zeros (vehicle v3c -> v3c2 -> v3d)
  Material changes                   the lead's materiality rule applied by m2_rebaseline_compare
  Actuator study                     every act_model 1 case (v2 set, + v3 set when present)
  J_int bracket                      n 4.8 on the governing supply (6.6 V both-stall plug voltage, sag) and the comparators
  CSI variants                       linear CSI summaries (with the 50 rad/s LPF + 100 deg/s slew), all variants
  Combustion OI cases                OI-1/OI-2 cases flown on the lead tank (v3 set)
Inputs (env, defaults as run): GNC_OUT_V2/GNC_RES_V2 (out/m2, out/results_v2), GNC_OUT_V3A/GNC_RES_V3A (out/m3a,
out/results_v3a), GNC_OUT_V3/GNC_RES_V3 (out/m3, out/results_v3), GNC_VEH_V2/V3A/V3 (vehicle dirs). Output:
GNC_RES_V3/report_tables_v3.md. Run: python scripts/m2_report_tables_v3.py
"""
import csv
import json
import os

S = "/home/claude/work/space/out"
O2 = os.environ.get("GNC_OUT_V2", f"{S}/m2")
R2 = os.environ.get("GNC_RES_V2", f"{S}/results_v2")
O3A = os.environ.get("GNC_OUT_V3A", f"{S}/m3a")
R3A = os.environ.get("GNC_RES_V3A", f"{S}/results_v3a")
O3 = os.environ.get("GNC_OUT_V3", f"{S}/m3")
R3 = os.environ.get("GNC_RES_V3", f"{S}/results_v3")
CASE_MAP = {"AD_prov_act_nmech_6V6_sagD": "AD_prov_act_n48_6V6_sagD",
            "AD_prov_act_nmech_6V6_J1_sagD": "AD_prov_act_n48_6V6_J1_sagD"}


def jl(p):
    try:
        with open(p) as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return None


def f(x, n=3):
    try:
        x = float(x)
    except (TypeError, ValueError):
        return "-" if x in (None, "") else str(x)
    if x != x:
        return "-"
    return f"{x:.{n}f}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def pci(s):
    if not s:
        return "-"
    return f"{s['success']:.3f} [{s['ci95'][0]:.3f}, {s['ci95'][1]:.3f}]"


def pair(rec):
    if not rec:
        return "-"
    flag = " LOSES" if rec.get("loses") else ""
    return f"-{rec['lost']}/+{rec['gained']}, p {rec['mcnemar_exact_p']:.2g}{flag}"


def ms(x):
    try:
        return f"{1e3 * float(x):.0f}"
    except (TypeError, ValueError):
        return "-"


def main():
    md = ["# Report tables v3 (generated by scripts/m2_report_tables_v3.py; do not edit by hand)\n"]
    S2 = (jl(os.path.join(O2, "mc6_summary_v2.json")) or {}).get("cases", {})
    S3a = (jl(os.path.join(O3A, "mc6_summary_v3a.json")) or {}).get("cases", {})
    S3 = (jl(os.path.join(O3, "mc6_summary_v3.json")) or {}).get("cases", {})
    rb_2_3a = jl(os.path.join(R3A, "rebaseline_v2_v3a.json")) or {}
    rb_3a_3 = jl(os.path.join(R3, "rebaseline_v3a_v3.json")) or {}
    rb_2_3 = jl(os.path.join(R3, "rebaseline_v2_v3.json")) or {}

    # ---------------- re-baseline attribution
    rows = []
    order = ["AD_fins_f20", "AD_prov_2kg", "AD_prov_act_n48_6V6_sagD", "AD_prov_act_nmech_6V6_sagD",
             "AD_prov_act_n48_6V6_J1_sagD", "AD_prov_act_nmech_6V6_J1_sagD"]
    for c in order:
        old = CASE_MAP.get(c, c)
        a, b, d = S2.get(old), S3a.get(old), S3.get(c)
        if not (a or b or d):
            continue
        r1 = (rb_2_3a.get("cases") or {}).get(old)
        r2 = (rb_3a_3.get("cases") or {}).get(c)
        r3 = (rb_2_3.get("cases") or {}).get(c)

        def g(x, k, n=3):
            return f(x.get(k), n) if x else "-"
        rows.append([c + (f" (v2/v3a: {old})" if old != c else ""),
                     pci(a["summary"]) if a else "-", pci(b["summary"]) if b else "-", pci(d["summary"]) if d else "-",
                     pair(r1), pair(r2), pair(r3),
                     " / ".join(g(x, "m_liftoff_kg") for x in (a, b, d)),
                     " / ".join(g(x, "m_n2o_sized_kg") for x in (a, b, d)),
                     " / ".join(f(x["summary"].get("td_vh_p99"), 2) if x else "-" for x in (a, b, d)),
                     " / ".join(f(x["summary"].get("max_hinge_max"), 1) if x else "-" for x in (a, b, d))])
    md.append("## Re-baseline attribution\n")
    md.append(table(["case", "P v2 [Wilson 95 %]", "P v3a", "P v3", "v2 -> v3a (lost/gained, McNemar p)",
                     "v3a -> v3", "v2 -> v3", "liftoff mass v2 / v3a / v3 [kg]", "N2O sized v2 / v3a / v3 [kg]",
                     "v_h p99 v2 / v3a / v3 [m/s]", "hinge max v2 / v3a / v3 [N m]"], rows))
    md.append("")

    # ---------------- vehicle
    rows = []
    vk = [("m_liftoff_kg", "liftoff mass (MC load) [kg]", 3), ("m_land_nominal_kg", "landing mass, nominal [kg]", 3),
          ("z_pivot_m", "pivot station [m]", 4), ("sums_dry_kg", "dry mass [kg]", 3),
          ("sums_propulsion_kg", "propulsion items [kg]", 3), ("sums_airframe_kg", "airframe items [kg]", 3),
          ("sums_gimballed_dry_kg", "gimballed dry mass [kg]", 4)]
    va, vb = rb_2_3a.get("vehicle") or {}, rb_2_3.get("vehicle") or {}
    for k, lab, n in vk:
        x2 = (va.get(k) or vb.get(k) or {}).get("old")
        x3a = (va.get(k) or {}).get("new")
        x3 = (vb.get(k) or {}).get("new")
        rows.append([lab, f(x2, n), f(x3a, n), f(x3, n)])
    md.append("## Vehicle re-baseline\n")
    md.append(table(["quantity", "v3c (gnc.json v2)", "v3c2 (combustion v2.1 on mechanical v1)", "v3d (mechanical v2)"],
                    rows))
    md.append("")
    tw2, tw3 = {(r["state"], r["F_label"]): r for r in rb_2_3a.get("twd") or []}, \
        {(r["state"], r["F_label"]): r for r in rb_2_3.get("twd") or []}
    rows = []
    for key in sorted(set(tw2) | set(tw3)):
        if key[1] not in ("12.5 %", "20.0 %", "hover (T=W)", "100.0 %"):
            continue
        a, b = tw2.get(key, {}), tw3.get(key, {})
        rows.append([key[0], key[1], f(a.get("w_twd_rad_s_old") or b.get("w_twd_rad_s_old"), 2),
                     f(a.get("w_twd_rad_s_new"), 2), f(b.get("w_twd_rad_s_new"), 2),
                     f(a.get("J_twd_kgm2_old") or b.get("J_twd_kgm2_old"), 4), f(b.get("J_twd_kgm2_new"), 4),
                     f(a.get("l_p_m_old") or b.get("l_p_m_old"), 3), f(b.get("l_p_m_new"), 3)])
    md.append("### Tail-wags-dog zeros\n")
    md.append(table(["state", "thrust", "w_twd v3c [rad/s]", "v3c2", "v3d", "J_twd v3c [kg m2]", "J_twd v3d",
                     "l_p v3c [m]", "l_p v3d"], rows))
    md.append("")

    # ---------------- material changes
    md.append("## Material changes\n")
    lines = []
    for nm, rb in (("v2 -> v3a (combustion.json v2.1 only)", rb_2_3a), ("v3a -> v3 (mechanical.json v2 only)", rb_3a_3),
                   ("v2 -> v3 (total)", rb_2_3)):
        if not rb:
            lines.append(f"- {nm}: not run")
            continue
        m = rb.get("material") or []
        lines.append(f"- {nm}: " + ("none under the rule" if not m else "; ".join(m)))
    rule = (rb_2_3 or rb_2_3a).get("rule")
    if rule:
        lines.append(f"- Rule: P {rule['P']}; liftoff mass {rule['liftoff_mass']}; tail-wags-dog zero {rule['twd']}.")
    md.append("\n".join(lines))
    md.append("")

    # ---------------- actuator study
    md.append("## Actuator study\n")
    rows = []
    for setname, path in (("v2", os.path.join(R2, "actuator_study_v2.json")), ("v3", os.path.join(R3, "actuator_study_v3.json"))):
        A = jl(path)
        if not A:
            continue
        for c, r in A["cases"].items():
            sat = r.get("saturation") or {}
            le = sat.get("longest_episode_s") or {}
            dh = sat.get("delivered_hinge_moment_Nm") or {}
            pv = sat.get("plug_voltage_min_V") or {}
            im = sat.get("servo_current_max_A") or {}
            pr = r.get("paired") or {}
            sup = (f"sag {r['V_hold_plug']:.2f} V hold" + (f" (rest {r['supply_Vrest']:.2f})" if r.get("supply_Vrest") else "")
                   if r.get("supply_chain") else f"fixed {r['servo_V']:.2f} V")
            rows.append([setname, c, f(r.get("n"), 1) if r.get("n") else "mech", sup, f"{r.get('J_int_servo_kgm2', 0):g}",
                         f"{r['P']:.3f} [{r['ci95'][0]:.3f}, {r['ci95'][1]:.3f}]", pair(pr.get("AD_prov_2kg")),
                         pair(pr.get("n6_same_supply")) if pr.get("n6_same_supply") else "-",
                         f(sat.get("frac_runs_saturated"), 2), ms(le.get("p99")), ms(le.get("max")),
                         f(r.get("holding_moment_neutral_weakest_Nm"), 2), f(dh.get("p99"), 1) + " / " + f(dh.get("max"), 1),
                         f(pv.get("min"), 2), f(im.get("max"), 2)])
    md.append(table(["set", "case", "n", "supply", "J_int [kg m2]", "P [Wilson 95 %]", "vs same vehicle, reference servo",
                     "vs n 6 twin", "runs saturated", "longest episode p99 [ms]", "longest max [ms]",
                     "holding moment [N m]", "delivered hinge p99 / max [N m]", "plug V min", "servo I max [A]"], rows))
    md.append("")

    # ---------------- J_int bracket
    md.append("## J_int bracket\n")
    A = jl(os.path.join(R2, "actuator_study_v2.json")) or {"cases": {}}
    rows = []
    sel = [(c, r) for c, r in A["cases"].items() if r.get("n") == 4.8 and r.get("supply_chain") and abs(r["V_hold_plug"] - 6.6) < 1e-6
           and not r.get("supply_Vrest")]
    sel.sort(key=lambda x: x[1].get("J_int_servo_kgm2", 0.0))
    for c, r in sel:
        sat = r.get("saturation") or {}
        le = sat.get("longest_episode_s") or {}
        pr = r.get("paired") or {}
        enb = "PASS" if (le.get("p99") is not None and le["p99"] <= 0.1) else "FAIL"
        rows.append([f"{r.get('J_int_servo_kgm2', 0.0):g}", f"{r['P']:.3f} [{r['ci95'][0]:.3f}, {r['ci95'][1]:.3f}]",
                     pair(pr.get("AD_prov_2kg")), ms(le.get("p99")), ms(le.get("max")), enb, c])
    md.append(table(["J_int [kg m2]", "P [Wilson 95 %]", "vs same vehicle, reference servo (lost/gained, p)",
                     "longest saturation episode p99 [ms]", "max [ms]", "ENG-07b (p99 <= 100 ms)", "case"], rows))
    md.append("")

    # ---------------- CSI variants
    md.append("## CSI variants\n")
    rows = []
    for nm, path in (("v2 (n 6, mechanical v1)", os.path.join(O2, "csi_v2.json")), ("v2_n48", os.path.join(O2, "csi_v2_n48.json")),
                     ("v2_n48_J2", os.path.join(O2, "csi_v2_n48_J2.json")), ("v2_n60_J2", os.path.join(O2, "csi_v2_n60_J2.json")),
                     ("v3 (mechanical v2)", os.path.join(O3, "csi_v3.json")), ("v3_J1", os.path.join(O3, "csi_v3_J1.json"))):
        c = jl(path)
        if not c:
            continue
        s = c["summary"].get("lpf", {})
        s0 = c["summary"].get("nofilt", {})
        var = c.get("variant") or {}
        rf, rl = c["rocking_full"], c["rocking_landing"]
        rows.append([nm, f(var.get("n"), 1) if var.get("n") else "as published",
                     f"{var.get('J_int_servo_kgm2', 0.0):g}",
                     f"{rf['f_rock_Hz'][0]:.1f}-{rf['f_rock_Hz'][1]:.1f} / {rl['f_rock_Hz'][0]:.1f}-{rl['f_rock_Hz'][1]:.1f}",
                     f"{s.get('n_unstable')}/{s.get('n_cases')}", f(s.get("flex_gm_up_min_dB"), 2), f(s.get("rigid_pm_min_deg"), 1),
                     f(s.get("rigid_gm_up_min_dB"), 2), f"{s0.get('n_unstable')}/{s0.get('n_cases')}",
                     "; ".join(s.get("flex_unstable") or []) or "none"])
    md.append(table(["variant", "n", "J_int [kg m2]", "rocking mode full / landing [Hz]", "unstable corners (LPF on)",
                     "min flex gain margin [dB]", "min rigid phase margin [deg]", "min rigid gain margin [dB]",
                     "unstable corners (no filter)", "unstable corners named (LPF on)"], rows))
    md.append("")

    # ---------------- combustion OI cases
    md.append("## Combustion OI cases\n")
    rows = []
    for c in ("AD_prov_2kg", "AD_prov_plant2", "AF_prov_2kg", "B_prov_2kg_h100", "B_prov_2kg_h50"):
        x = S3.get(c)
        if not x:
            continue
        s = x["summary"]
        nom = x.get("nominal") or {}
        rows.append([c, x.get("note", "")[:110], pci(s), f(x.get("m_n2o_sized_kg"), 3), f(x.get("m_n2o_mc_kg"), 3),
                     ";".join(f"{k}:{v}" for k, v in (s.get("fail_modes") or {}).items()) or "none",
                     f(s.get("prop_used_p99"), 3), f(s.get("liq_left_p01"), 3), f(nom.get("burn_total", nom.get("t_burn")), 2),
                     f(nom.get("h_max"), 1), f(s.get("td_vh_p99"), 2)])
    md.append(table(["case", "configuration", "P [Wilson 95 %]", "N2O sized [kg]", "N2O flown [kg]", "failure modes",
                     "propellant used p99 [kg]", "liquid left p01 [kg]", "nominal burn [s]", "nominal apex [m]",
                     "v_h p99 [m/s]"], rows))
    md.append("")
    dest = os.path.join(R3, "report_tables_v3.md")
    os.makedirs(R3, exist_ok=True)
    with open(dest, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("written", dest)


if __name__ == "__main__":
    main()
