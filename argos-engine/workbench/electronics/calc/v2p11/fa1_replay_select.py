#!/usr/bin/env python3
"""Electronics v2.11 (2026-10-13): FA-1 replay cases for the SIL S9R relight-window study (LEAD CHANGELOG 203 (1)(b) ride-through
CANDIDATE, 205 C1 chain). Selects Combustion FA-1 head-pressure histories from the 896-case grid by the v2.11 harness metrics on the
default SIL chain (c1_cc2_c222_v6, results/fa1_chain_v2p11_cases.csv) and writes them as a generated header for the SIL
(firmware/sil/fa1_replay_cases.h). Histories: 02-combustion/data/v2p4a/fa1_envelope_v2p4a.json (read-only), P_head_hist_bar, 0.1 ms grid,
0-25 ms from the light, each value clipped below at state.P0_cold_flow_Pa (as calc/v2p10/fa1_overrange.py extract).
Selection (DESIGN, worst-first by the harness metric; ties -> lowest case index):
  max_face   : largest diaphragm (face) peak on the chain
  max_c30    : longest continuous filtered > 30 bar abs (the ride-through persistence driver)
  max_end    : latest end of a filtered > 30 bar episode after E2 (the window-end driver)
  max_t45    : longest continuous raw reading > 45 bar abs (the T45 guard driver)
  max_filt   : largest filtered (50 Hz) peak
  med_abort  : median face peak among the cases the as-built firmware 5 ms rule aborts
  max_noabort: largest face peak among the cases the as-built chain does not abort (no fw 5 ms trip, no low-band comparator trip)
Tags: the histories are Combustion SIM on an ASSUMED construct; the selection is DESIGN; nothing here is hardware evidence.
Usage: python3 calc/v2p11/fa1_replay_select.py [--engine-root ...] [--chain c1_cc2_c222_v6]
"""
import argparse
import csv
import hashlib
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def sha16(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()[:16]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--engine-root', default='/home/claude/work/shared-fallback/engine')
    ap.add_argument('--chain', default='c1_cc2_c222_v6')
    ap.add_argument('--cases-csv', default=os.path.join(ROOT, 'results', 'fa1_chain_v2p11_cases.csv'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'firmware', 'sil', 'fa1_replay_cases.h'))
    a = ap.parse_args()
    src = os.path.join(a.engine_root, '02-combustion', 'data', 'v2p4a', 'fa1_envelope_v2p4a.json')
    d = json.load(open(src))
    keys = list(d['cases'].keys())
    p0 = d['state']['P0_cold_flow_Pa'] / 1e5
    grid = d['history_grid_ms']
    assert len(grid) == 251 and abs(grid[1] - 0.1) < 1e-9, 'history grid changed'
    rows = [r for r in csv.DictReader(open(a.cases_csv)) if r['chain'] == a.chain]
    assert len(rows) == len(keys) == 896, (len(rows), len(keys))
    F = lambda r, k: float(r[k])
    I = lambda r, k: int(r[k])
    def worst(metric, pool=None):
        pool = rows if pool is None else pool
        return max(pool, key=lambda r: (F(r, metric), -I(r, 'case')))
    sel = {}
    sel['max_face'] = worst('face_pk_bar')
    sel['max_c30'] = worst('c30f_ms')
    sel['max_end'] = worst('c30_end_rel_E2_ms')
    sel['max_t45'] = worst('t45c_ms')
    sel['max_filt'] = worst('filt_pk_bar')
    ab = sorted([r for r in rows if I(r, 'fw5')], key=lambda r: (F(r, 'face_pk_bar'), I(r, 'case')))
    sel['med_abort'] = ab[len(ab) // 2]
    na = [r for r in rows if not I(r, 'fw5') and not I(r, 'clo_asb')]
    sel['max_noabort'] = worst('face_pk_bar', na)
    out = []
    for tag, r in sel.items():
        i = I(r, 'case')
        h = [max(v, p0) for v in d['cases'][keys[i]]['P_head_hist_bar']]
        out.append((tag, i, keys[i], r, h))
    L = ['// GENERATED by calc/v2p11/fa1_replay_select.py - DO NOT EDIT. FA-1 relight head-pressure histories for the SIL S9R replay',
         '// (bar abs, 0.1 ms grid, 0-25 ms from the light; clipped below at P0 %.4f bar abs). Source %s %s (Combustion SIM on an ASSUMED'
         % (p0, os.path.relpath(src, a.engine_root), sha16(src)),
         '// construct); selection on %s (results/fa1_chain_v2p11_cases.csv %s, DESIGN). Not hardware evidence.' % (a.chain, sha16(a.cases_csv)),
         '#pragma once', 'namespace sil {', 'namespace fa1rep {', 'struct Case { const char* tag; int index; const char* key; double face_pk_bar, c30f_ms, '
         'end_rel_E2_ms, t45c_ms, filt_pk_bar; bool asb_fw5, asb_cmp_low; double h[251]; };', 'constexpr int kN = %d;' % len(out),
         'constexpr Case kCases[kN] = {']
    for tag, i, key, r, h in out:
        L.append('  {"%s", %d, "%s", %.3f, %.1f, %.1f, %.1f, %.3f, %s, %s,' % (tag, i, key, F(r, 'face_pk_bar'), F(r, 'c30f_ms'), F(r, 'c30_end_rel_E2_ms'),
                 F(r, 't45c_ms'), F(r, 'filt_pk_bar'), 'true' if I(r, 'fw5') else 'false', 'true' if I(r, 'clo_asb') else 'false'))
        for k in range(0, 251, 12):
            L.append('   ' + ' '.join('%.4f,' % v for v in h[k:k + 12]))
        L[-1] = L[-1].rstrip(',')
        L.append('   }},')
    L += ['};', '}  // namespace fa1rep', '}  // namespace sil', '']
    open(a.out, 'w').write('\n'.join(L))
    for tag, i, key, r, h in out:
        print('%-11s case %3d %-60s head pk %6.2f face %6.2f c30 %4.1f end %+5.1f t45 %3.1f filt %5.2f fw5 %s' % (
            tag, i, key, max(h), F(r, 'face_pk_bar'), F(r, 'c30f_ms'), F(r, 'c30_end_rel_E2_ms'), F(r, 't45c_ms'), F(r, 'filt_pk_bar'), r['fw5']))
    print('wrote', os.path.relpath(a.out, ROOT), sha16(a.out))


if __name__ == '__main__':
    main()
